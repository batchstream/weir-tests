#!/usr/bin/env python3
"""Render every retained comparison, including all rounds and resource costs."""

import argparse
import json
from pathlib import Path


ROLES = (("primary", "Independent single-record requests"),
         ("lua", "Fixed atomic transform against native update controls"),
         ("ablation", "Same-run aggregation ablation"),
         ("cpu2", "Two-CPU database sensitivity"),
         ("bulk", "Native bulk control, 32 records per call"))


def numbers(values, digits=1):
    return " / ".join("NA" if value is None else f"{value:,.{digits}f}" for value in values)


def work(row):
    if row["lua"]:
        return "Transform"
    return {0: "Read", 10: "90/10", 100: "Write"}[row["requested_write_percent"]]


def identity(row):
    return row["label"], row["backend"], row["concurrency"]


def latency(row, percentile):
    pooled = row.get("pooled_single_request_latency")
    if pooled is not None:
        return f"{pooled['p' + str(percentile) + '_upper_ns'] / 1e6:.3f}"
    bounds = row["round_p" + str(percentile) + "_upper_ns_range"]
    return numbers([bound / 1e6 for bound in bounds], 3) + " (round range)"


def render(report):
    paths = {}
    for row in report["aggregates"]:
        paths.setdefault(identity(row), {})[row["path"]] = row
    lines = ["# Complete measured comparisons", "",
             "Generated by `tables.py` from `analysis.json`. All 94 comparisons are retained.",
             "Rates are total successful records / total elapsed seconds; parentheses contain",
             "rounds 1 / 2 / 3. Ratios compare Weir with the paired native path. No round is discarded.", "",
             "Latency numbers are histogram upper bounds in milliseconds (approximation ≤12.5% + 1µs).",
             "Single-request quantiles pool raw buckets; bulk quantiles show the range of the three",
             "round quantiles, not a pooled percentile. DB CPU is a percentage of the inspected",
             "database quota, shown separately for every round. CPU values may slightly exceed 100%",
             "because cgroup accounting and sampling boundaries differ. Weir CPU is the Prometheus",
             "counter-window microseconds / successful record; it includes metrics collection overhead.",
             "RSS is a sampled maximum, and client RSS is the simultaneous sum across processes.",
             "Native rows still have an idle Weir process in the fixture; the cost table reports",
             "active-path Weir RSS only. These are not total-host cost measurements.", "",
             "Mongo command counts cover only the selected business command types in METHOD.md.",
             "Search physical HTTP-command counts and bulk client-process RSS are unavailable (`NA`).",
             "The adapter average is operations / adapter invocations, distinct from physical commands.", ""]
    for role, title in ROLES:
        comparisons = [row for row in report["comparisons"] if row["role"] == role]
        comparisons.sort(key=lambda row: (row["backend"], row["requested_write_percent"], row["backend_batch_limit"], row["concurrency"]))
        lines.extend(["## " + title, "", "| Backend | Work | Group limit | Workers | Native records/s (R1 / R2 / R3) | Weir records/s (R1 / R2 / R3) | Change | Paired ratios R1 / R2 / R3 |", "| --- | --- | ---: | ---: | --- | --- | ---: | --- |"])
        for row in comparisons:
            direct, weir = paths[identity(row)]["direct"], paths[identity(row)]["weir"]
            prefix = f"| {row['backend']} | {work(row)} | {row['backend_batch_limit']} | {row['concurrency']} |"
            if not row["qualified"]:
                lines.append(prefix + " FAILED | FAILED | NA | NA |")
                continue
            lines.append(prefix + f" {direct['qps']:,.1f} ({numbers(direct['round_qps'])}) | {weir['qps']:,.1f} ({numbers(weir['round_qps'])}) | {row['weir_qps_delta_percent']:+.1f}% | {numbers(row['round_weir_direct_qps_ratios'], 3)} |")
        lines.extend(["", "| Backend | Work | Group | Workers | Native p95 / p99 ms | Weir p95 / p99 ms |", "| --- | --- | ---: | ---: | --- | --- |"])
        for row in comparisons:
            direct, weir = paths[identity(row)]["direct"], paths[identity(row)]["weir"]
            lines.append(f"| {row['backend']} | {work(row)} | {row['backend_batch_limit']} | {row['concurrency']} | {latency(direct, 95)} / {latency(direct, 99)} | {latency(weir, 95)} / {latency(weir, 99)} |")
        lines.extend(["", "| Backend | Work | Group | Workers | DB CPU native, R1 / R2 / R3 | DB CPU Weir, R1 / R2 / R3 | Weir CPU µs/record | Weir RSS MiB | Client RSS native / Weir MiB | Selected commands/record native / Weir | Weir adapter average |", "| --- | --- | ---: | ---: | --- | --- | ---: | ---: | --- | --- | ---: |"])
        for row in comparisons:
            direct, weir = paths[identity(row)]["direct"], paths[identity(row)]["weir"]
            cpu = numbers([weir["weir_prometheus_cpu_us_per_success"]])
            rss = numbers([weir["weir_peak_rss_bytes"] / 2**20])
            clients = [path["client_simultaneous_peak_rss_bytes"] / 2**20 if path["client_simultaneous_peak_rss_bytes"] is not None else None for path in (direct, weir)]
            commands = [path["selected_mongo_commands_per_success"] for path in (direct, weir)]
            lines.append(f"| {row['backend']} | {work(row)} | {row['backend_batch_limit']} | {row['concurrency']} | {numbers(direct['round_database_cpu_budget_percent'])} | {numbers(weir['round_database_cpu_budget_percent'])} | {cpu} | {rss} | {numbers(clients)} | {numbers(commands, 4)} | {numbers([weir['adapter_batch_average']], 3)} |")
        lines.append("")
    return "\n".join(lines).rstrip()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--analysis", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    report = json.loads(args.analysis.read_text())
    args.output.write_text(render(report) + "\n")


if __name__ == "__main__":
    main()
